export type IconName = keyof typeof GLYPHS;

export type IconProps = Omit<SVGProps<SVGSVGElement>, "children" | "viewBox" | "name"> & {
  readonly name: IconName;
  /** The drawn size in px. A glyph keeps its own grid, so 14 draws a 16 grid smaller. */
  readonly size?: number;
};

/**
 * One of Cycle's icons. It is decorative unless given an `aria-label`, so an icon-only button
 * still needs its own accessible name.
 */
export const Icon = memo(function Icon({ name, size, className, ...props }: IconProps) {
  const glyph: Glyph = GLYPHS[name];
  const grid = glyph.size ?? 16;
  const drawn = size ?? grid;
  return (
    <svg
      aria-hidden={props["aria-label"] === undefined ? true : undefined}
      width={drawn}
      height={drawn}
      {...props}
      className={className ? `icon ${className}` : "icon"}
      viewBox={`0 0 ${grid} ${grid}`}
      fill="none"
      stroke="currentColor"
      strokeWidth={1.25}
      strokeLinecap="round"
      strokeLinejoin="round"
      data-icon={name}
    >
      {glyph.paths.map((path, index) =>
        typeof path === "string" ? <path key={index} d={path} /> : <path key={index} {...path} />,
      )}
    </svg>
  );
});

/** Something is at work: the loader glyph, turning. It keeps turning under Reduce Motion. */
export const Spinner = memo(function Spinner({
  size = 16,
  className,
}: {
  readonly size?: number;
  readonly className?: string;
}) {
  return <Icon name="loader" size={size} className={className ? `spin ${className}` : "spin"} />;
});

/** A background task at work: a dot in the background color that breathes. */
export const BackgroundDot = memo(function BackgroundDot() {
  return <span aria-hidden className="background-dot" />;
});
