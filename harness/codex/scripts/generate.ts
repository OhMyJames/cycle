// Keep the notification types we consume and their transitive type imports from this exact CLI.
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { nativeBinary } from "../src/binary.ts";

const temp = await mkdtemp(join(tmpdir(), "cycle-codex-types-"));
try {
  const proc = Bun.spawn(
    [nativeBinary(), "app-server", "generate-ts", "--out", join(temp, "schema")],
    { cwd: temp, env: { HOME: temp, CODEX_HOME: temp, PATH: "/usr/bin:/bin" }, stderr: "inherit" },
  );
  if ((await proc.exited) !== 0) throw new Error("generate-ts failed");
  const seen = new Set<string>();
  const parts = ["// Generated by harness/codex/scripts/generate.ts from the pinned Codex CLI.\n"];
  async function collect(path: string) {
    if (seen.has(path)) return;
    seen.add(path);
    const source = await readFile(path, "utf8");
    for (const match of source.matchAll(/^import type .* from "(.*)";/gm))
      await collect(resolve(dirname(path), `${match[1]}.ts`));
    parts.push(source.slice(source.indexOf("export type ")));
  }
  for (const name of [
    "ItemCompletedNotification",
    "TurnCompletedNotification",
    "AgentMessageDeltaNotification",
    "UserInput",
    "CommandExecutionRequestApprovalParams",
    "FileChangeRequestApprovalParams",
    "PermissionsRequestApprovalParams",
    "ModelListResponse",
    "Model",
    "ReasoningEffortOption",
  ])
    await collect(join(temp, "schema/v2", `${name}.ts`));
  await writeFile(new URL("../src/wire.generated.ts", import.meta.url), parts.join("\n"));
} finally {
  await rm(temp, { recursive: true, force: true });
}
